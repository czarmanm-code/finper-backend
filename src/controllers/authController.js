import crypto from 'crypto'
import jwt from 'jsonwebtoken'
import User from '../models/User.js'
import Invitation from '../models/Invitation.js'
import { seedDefaultCategoriesForUser } from '../utils/seedDefaults.js'

function generateToken(user) {
  const secret = process.env.JWT_SECRET || 'supersecretjwtkey_finper_dev_mode_change_in_production'
  const expiresIn = process.env.JWT_EXPIRES_IN || '7d'

  return jwt.sign(
    {
      id: user._id.toString(),
      email: user.email,
      role: user.role,
    },
    secret,
    { expiresIn }
  )
}

/**
 * Register a new user.
 * System bootstrap: First user registered automatically becomes 'admin'.
 * Subsequent users require a valid, unused invitation token generated by an admin.
 */
export async function register(req, res) {
  const { name, email, password, invitationToken } = req.body

  if (!name || !email || !password) {
    return res.status(400).json({
      message: 'Name, email, and password are required',
    })
  }

  const existingUser = await User.findOne({ email: email.toLowerCase() })
  if (existingUser) {
    return res.status(409).json({
      message: 'A user with this email address already exists',
    })
  }

  const totalUsers = await User.countDocuments()
  let role = 'user'
  let invitedBy = null
  let invitation = null

  if (totalUsers === 0) {
    // Initial bootstrap: make the first user admin
    role = 'admin'
  } else {
    // Require invitation token for new users
    if (!invitationToken) {
      return res.status(400).json({
        message: 'An invitation token is required to register',
      })
    }

    invitation = await Invitation.findOne({ token: invitationToken })
    if (!invitation) {
      return res.status(400).json({
        message: 'Invalid invitation token',
      })
    }

    if (invitation.used) {
      return res.status(400).json({
        message: 'This invitation token has already been used',
      })
    }

    if (new Date() > invitation.expiresAt) {
      return res.status(400).json({
        message: 'This invitation token has expired',
      })
    }

    role = invitation.assignedRole || 'user'
    invitedBy = invitation.createdBy
  }

  const user = await User.create({
    name,
    email: email.toLowerCase(),
    password,
    role,
    invitedBy,
    isActive: true,
  })

  // Automatically provision default categories for new user
  await seedDefaultCategoriesForUser(user._id)

  if (invitation) {
    invitation.used = true
    invitation.usedBy = user._id
    await invitation.save()
  }

  const token = generateToken(user)

  return res.status(201).json({
    message: 'User registered successfully',
    token,
    user: {
      id: user._id.toString(),
      name: user.name,
      email: user.email,
      role: user.role,
      invitedBy: user.invitedBy,
    },
  })
}

/**
 * Log in an existing user.
 */
export async function login(req, res) {
  const { email, password } = req.body

  if (!email || !password) {
    return res.status(400).json({
      message: 'Email and password are required',
    })
  }

  const user = await User.findOne({ email: email.toLowerCase() }).select('+password')
  if (!user) {
    return res.status(401).json({
      message: 'Invalid credentials',
    })
  }

  if (!user.isActive) {
    return res.status(403).json({
      message: 'Your account has been deactivated. Please contact an administrator.',
    })
  }

  const isMatch = await user.comparePassword(password)
  if (!isMatch) {
    return res.status(401).json({
      message: 'Invalid credentials',
    })
  }

  // Provision default categories if user has zero categories
  await seedDefaultCategoriesForUser(user._id)

  const token = generateToken(user)

  return res.status(200).json({
    message: 'Login successful',
    token,
    user: {
      id: user._id.toString(),
      name: user.name,
      email: user.email,
      role: user.role,
    },
  })
}

/**
 * Get profile of the current authenticated user.
 */
export async function getProfile(req, res) {
  return res.status(200).json({
    user: {
      id: req.user._id.toString(),
      name: req.user.name,
      email: req.user.email,
      role: req.user.role,
      isActive: req.user.isActive,
      createdAt: req.user.createdAt,
    },
  })
}

/**
 * Admin endpoint: Generate an invitation token and link.
 */
export async function generateInvitation(req, res) {
  const { assignedRole = 'user', expiresInDays = 7 } = req.body

  if (!['admin', 'user'].includes(assignedRole)) {
    return res.status(400).json({
      message: 'assignedRole must be either "admin" or "user"',
    })
  }

  const token = crypto.randomBytes(24).toString('hex')
  const expiresAt = new Date()
  expiresAt.setDate(expiresAt.getDate() + Number(expiresInDays))

  const invitation = await Invitation.create({
    token,
    createdBy: req.user._id,
    assignedRole,
    expiresAt,
  })

  return res.status(201).json({
    message: 'Invitation generated successfully',
    invitation: {
      id: invitation._id.toString(),
      token: invitation.token,
      assignedRole: invitation.assignedRole,
      expiresAt: invitation.expiresAt,
      inviteLink: `/register?token=${invitation.token}`,
    },
  })
}

/**
 * Admin endpoint: List all invitations.
 */
export async function listInvitations(req, res) {
  const invitations = await Invitation.find()
    .populate('createdBy', 'name email')
    .populate('usedBy', 'name email')
    .sort({ createdAt: -1 })

  return res.status(200).json({ invitations })
}

/**
 * Admin endpoint: List all users in the system.
 */
export async function listUsers(req, res) {
  const users = await User.find()
    .populate('invitedBy', 'name email')
    .sort({ createdAt: -1 })

  return res.status(200).json({ users })
}

